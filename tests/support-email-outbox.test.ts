import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import { join } from "node:path"
import test from "node:test"

function read(path: string) {
  return readFileSync(join(process.cwd(), path), "utf8")
}

test("support replies use a durable authenticated outbox", () => {
  const worker = read("src/lib/support-email-outbox.ts")
  const route = read("src/app/api/email/support-outbox/route.ts")
  const config = read("vercel.json")
  const script = read("scripts/queue-support-email.ts")
  const gmail = read("src/lib/support-gmail.ts")
  const branding = read("src/lib/support-email-branding.ts")
  const googleCallback = read("src/app/api/google/callback/route.ts")
  const schema = read("prisma/schema.prisma")
  const monitoring = read("src/lib/operational-monitoring.ts")

  assert.match(worker, /deliveryKey/)
  assert.match(worker, /sendSupportGmail/)
  assert.match(worker, /deliveryKey: candidate\.deliveryKey/)
  assert.doesNotMatch(worker, /sendTransactionalEmail/)
  assert.match(worker, /MAX_DELIVERY_ATTEMPTS = 8/)
  assert.match(worker, /status: "SENT"/)
  assert.match(worker, /targetReportStatus/)
  assert.match(worker, /recordOperationalEvent/)
  assert.match(worker, /reconcileSupportEmailDelivery/)
  assert.match(worker, /api\.resend\.com\/emails/)
  assert.match(worker, /providerStatus: "DELIVERED"/)
  assert.match(worker, /terminalDeliveryStatuses/)
  assert.match(worker, /providerStatus: `gmail_sent:/)
  assert.match(worker, /verifySupportGmailSentMessage/)
  assert.match(worker, /gmail_sent_verified:/)
  assert.match(worker, /if \(reconciled\.count !== 1\) return false/)
  assert.match(worker, /recorded\.count === 1 \? "gmail_verification_failed" : "already_reconciled"/)
  assert.doesNotMatch(worker, /lastError: reason \}, where: \{ id: message\.id \} \}/)
  assert.match(worker, /GMAIL_MESSAGE_MISSING/)
  assert.match(worker, /GMAIL_SENT_LABEL_MISSING/)
  assert.match(worker, /createdAt: \{ gt: message\.createdAt \}/)
  assert.match(worker, /&& !newerReportResponse/)
  assert.match(worker, /isCurrentSupportResponse/)
  assert.match(worker, /else if \(currentReportResponse\)/)
  assert.match(worker, /OPT_OUT_SOURCES = new Set\(\["checkout_completion_nudge"\]\)/)
  assert.match(worker, /PLAIN_TEXT_SOURCES = new Set\(\["support_delivery_recovery_plain_text"\]\)/)
  assert.match(worker, /return \{ body: candidate\.body, html: "" \}/)
  assert.match(worker, /Recovered by a newer verified support response\./)
  assert.match(worker, /status: "SUPERSEDED"/)
  assert.match(worker, /await supersedeRecoveredFailures\(tx, message\)/)
  assert.match(worker, /createEmailUnsubscribeToken\(candidate\.toEmail\)/)
  assert.match(worker, /Unsubscribe from enrollment reminders and product education/)
  assert.match(worker, /OWNER_COMPLETION_COPY_SOURCE = "support_resolution_owner_copy"/)
  assert.match(worker, /owner-copy:\$\{message\.deliveryKey\}/)
  assert.match(worker, /targetReportStatus !== "FIXED"/)
  assert.match(worker, /lifecycleState: "OWNER_COPY_PENDING"/)
  assert.match(worker, /message\.source === OWNER_COMPLETION_COPY_SOURCE/)
  assert.match(worker, /where: \{ deliveryKey: ownerCopy\.deliveryKey \}/)
  assert.match(route, /hasAuthorizedBearerSecret/)
  assert.match(config, /\/api\/email\/support-outbox/)
  assert.match(config, /\*\/5 \* \* \* \*/)
  assert.match(script, /body-base64/)
  assert.match(script, /subject-base64/)
  assert.match(branding, /PHOTOVIEW_SUPPORT_EMAIL = getSupportBrand\(\)\.supportEmail/)
  assert.match(read("src/lib/support-brands.ts"), /supportEmail: "support@photoview\.io"/)
  assert.match(read("src/lib/support-brands.ts"), /ownerCompletionEmail: "mitch@photoview\.io"/)
  assert.doesNotMatch(branding, /process\.env\.SUPPORT_EMAIL/)
  assert.doesNotMatch(branding, /process\.env\.SUPPORT_EMAIL_FROM/)
  assert.match(gmail, /return supportEmailAddress\(\)/)
  assert.match(gmail, /users\/me\/messages\/send/)
  assert.match(gmail, /rfc822msgid:/)
  assert.match(gmail, /supportGmailMessageId/)
  assert.match(gmail, /verifySupportGmailSentMessage/)
  assert.match(gmail, /labelIds\?\.includes\("SENT"\)/)
  assert.match(googleCallback, /saveSupportGoogleConnection/)
  assert.match(schema, /model SupportGoogleConnection/)
  assert.match(monitoring, /failedSupportEmails/)
  assert.match(monitoring, /supportGmailConnected/)
})
